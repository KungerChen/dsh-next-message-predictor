// Build lib/client.js from src/shared + src/client without any bundler.
//
// The DSH Web host loads a client module as a `window.__ModuleLoader__` factory.
// We keep that format by concatenating the shared modules (which the Host also
// imports as ESM) into the factory body, stripping their `export `/`import`
// syntax. This is intentionally dependency-free: no toolchain, no network.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const PACKAGE_NAME = 'dsh-next-message-predictor'

const INPUTS = [
  'src/shared/version.js',
  'src/shared/config.js',
  'src/shared/presets.js',
  'src/shared/protocol.js',
  'src/shared/output-validation.js',
  'src/client/locales/zh.js',
  'src/client/locales/en.js',
  'src/client/locales/ja.js',
  'src/client/locales/ko.js',
  'src/client/locales/es.js',
  'src/client/locales/fr.js',
  'src/client/locales/de.js',
  'src/client/locales/ru.js',
  'src/client/locales/pt.js',
  'src/client/i18n.js',
  'src/client/dom.js',
  'src/client/labels.js',
  'src/client/controller.js',
  'src/client/overlay.js',
  'src/client/settings.js',
  'src/client/index.js',
]

/** Remove ES module import statements (single- and multi-line). */
function stripImports(source) {
  return source.replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];?[ \t]*$/gm, '')
}

/** Remove `export ` keywords so declarations land in the factory scope. */
function stripExports(source) {
  return source
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+\{[^}]*\}\s*;?[ \t]*$/gm, '')
    .replace(/^export\s+const\s+/gm, 'const ')
    .replace(/^export\s+let\s+/gm, 'let ')
    .replace(/^export\s+function\s+/gm, 'function ')
    .replace(/^export\s+async\s+function\s+/gm, 'async function ')
}

// One version everywhere: package.json is what DSH shows in its plugin list,
// src/shared/version.js is what the Settings header and the Host report.
const packageVersion = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version
const sourceVersion = /PLUGIN_VERSION\s*=\s*'([^']+)'/.exec(readFileSync(join(root, 'src/shared/version.js'), 'utf8'))?.[1]
if (sourceVersion !== packageVersion) {
  throw new Error(`version mismatch: package.json is ${packageVersion}, src/shared/version.js is ${sourceVersion}`)
}

const chunks = []
const declared = new Map()
for (const relative of INPUTS) {
  const absolute = join(root, relative)
  const raw = readFileSync(absolute, 'utf8')
  const body = stripExports(stripImports(raw)).trim()
  if (body === '') throw new Error(`empty module after stripping: ${relative}`)
  if (/^\s*(import|export)\s/m.test(body)) throw new Error(`import/export left after stripping: ${relative}`)
  // All modules share one function scope in the bundle: a top-level name
  // declared twice would be a SyntaxError in the browser, so catch it here.
  for (const match of body.matchAll(/^(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    const name = match[1]
    if (declared.has(name)) throw new Error(`"${name}" is declared in both ${declared.get(name)} and ${relative}`)
    declared.set(name, relative)
  }
  chunks.push(`// ===== ${relative} =====\n${body}`)
}

const bundle = `// GENERATED by scripts/build-client.mjs — edit src/client/*.js or src/shared/*.js instead.
// dsh-next-message-predictor ${packageVersion} (browser half).
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_NAME)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    var react = require("react");

${chunks.join('\n\n')}

    var client = createClient(react);
    module.exports = { inject: client.inject, apply: client.apply };
    module.exports.default = client;
    return module.exports;
  },
});
`

// The concatenated factory must parse; a broken bundle would fail silently in
// the browser (the plugin simply would not load).
try {
  new Function('window', bundle)
} catch (error) {
  throw new Error(`generated bundle does not parse: ${error instanceof Error ? error.message : String(error)}`)
}

const out = join(root, 'lib/client.js')
writeFileSync(out, bundle, 'utf8')
console.log(`built ${out} (${Buffer.byteLength(bundle, 'utf8')} bytes)`)
