import test from 'node:test'
import assert from 'node:assert/strict'
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import { applyBuildUpdate, computeBuildId, inspectLocalBuild, sha256File } from '../src/host/build-integrity.js'

function fixture(t) {
  const base = mkdtempSync(join(tmpdir(), 'nmp-build-'))
  t.after(() => rmSync(base, { recursive: true, force: true }))
  const root = join(base, 'package'), profile = join(base, 'profile')
  for (const dir of ['src/client', 'src/host', 'src/shared', 'locale', 'lib', 'scripts']) mkdirSync(join(root, dir), { recursive: true })
  mkdirSync(join(profile, 'node_modules'), { recursive: true })
  symlinkSync(root, join(profile, 'node_modules', 'dsh-next-message-predictor'), 'junction')
  for (const file of ['package.json', 'cordis.patch.yml', 'lib/index.js', 'icon.svg', 'scripts/build-client.mjs', 'src/client/a.js', 'src/host/a.js', 'src/shared/a.js', 'locale/en.json']) writeFileSync(join(root, file), file)
  const build = () => {
    const id = computeBuildId(root)
    writeFileSync(join(root, 'src/shared/build-id.js'), `// Generated by scripts/build-client.mjs. Do not edit.\nexport const PLUGIN_BUILD_ID = '${id}'\n`)
    writeFileSync(join(root, 'lib/client.js'), `const PLUGIN_BUILD_ID = '${id}'`)
    writeFileSync(join(root, 'lib/build-manifest.json'), JSON.stringify({ buildId: id, clientSha256: sha256File(join(root, 'lib/client.js')) }))
    return id
  }
  return { base, root, profile, build }
}

test('content identity is deterministic and detects incomplete builds and moved installs', (t) => {
  const f = fixture(t), id = f.build()
  assert.equal(computeBuildId(f.root), id)
  assert.equal(inspectLocalBuild(f.profile, true, f.root, id).state, 'current')
  writeFileSync(join(f.root, 'README.md'), 'documentation only')
  assert.equal(computeBuildId(f.root), id)
  writeFileSync(join(f.root, 'src/host/a.js'), 'changed')
  assert.equal(inspectLocalBuild(f.profile, true, f.root, id).state, 'unknown')
  const next = f.build()
  assert.deepEqual(inspectLocalBuild(f.profile, true, f.root, id), { runningId: id, installedId: next, state: 'update-available', canApply: true, reason: '' })
  assert.equal(inspectLocalBuild(f.profile, false, f.root, id).canApply, false)
  writeFileSync(join(f.root, 'lib/client.js'), 'incomplete')
  assert.equal(inspectLocalBuild(f.profile, true, f.root, id).state, 'unknown')
  assert.equal(inspectLocalBuild(f.profile, true, f.base, id).reason, 'installation-moved')
})

test('update is rechecked inside the exclusive lock and all HMR outcomes fail closed', async () => {
  const target = 'a'.repeat(64), calls = []
  let state = { state: 'update-available', installedId: target, canApply: true }
  let result = { warnings: [], pending: [] }
  const hmr = { async runExclusive(fn) { calls.push('lock'); return fn() }, async reconcileProfile(ids) { calls.push(ids); return result } }
  const apply = (overrides = {}) => applyBuildUpdate({ hmr, inspect: () => state, entryId: 'entry', targetBuildId: target, ...overrides })
  assert.equal(await apply(), '')
  assert.deepEqual(calls, ['lock', ['entry']])
  state = { ...state, installedId: 'b'.repeat(64) }
  assert.equal(await apply(), 'build-changed')
  state = { ...state, installedId: target, state: 'current' }
  assert.equal(await apply(), 'build-changed')
  state = { ...state, state: 'update-available' }
  result = { warnings: [], pending: [{ reason: 'stale' }] }
  assert.equal(await apply(), 'restart-required')
  result = { warnings: [], pending: [], restartReason: 'host-module' }
  assert.equal(await apply(), 'restart-required')
  result = { warnings: ['diagnostic'], pending: [] }
  assert.equal(await apply(), 'reconcile-failed')
  result = { warnings: [] }
  assert.equal(await apply(), 'reconcile-failed')
  result = { warnings: [], pending: {} }
  assert.equal(await apply(), 'reconcile-failed')
  assert.equal(await apply({ hmr: {} }), 'update-unavailable')
  const aborter = new AbortController(); aborter.abort()
  assert.equal(await apply({ signal: aborter.signal }), 'build-changed')
  assert.equal(await apply({ isActive: () => false }), 'build-changed')
})

test('a queued request from a disposed Host cannot reload the profile again', async () => {
  const target = 'c'.repeat(64)
  let active = true, reloads = 0, release
  let queue = Promise.resolve()
  const gate = new Promise(resolve => { release = resolve })
  const hmr = {
    runExclusive(fn) { const next = queue.then(fn); queue = next; return next },
    async reconcileProfile() { reloads += 1; await gate; active = false; return { warnings: [], pending: [] } },
  }
  const args = { hmr, inspect: () => ({ state: 'update-available', installedId: target, canApply: true }), entryId: 'entry', targetBuildId: target, isActive: () => active }
  const first = applyBuildUpdate(args), second = applyBuildUpdate(args)
  await new Promise(resolve => setTimeout(resolve, 0))
  release()
  assert.deepEqual(await Promise.all([first, second]), ['', 'build-changed'])
  assert.equal(reloads, 1)
})

test('build bootstraps missing generated identity and manifest', (t) => {
  const base = mkdtempSync(join(tmpdir(), 'nmp-build-bootstrap-'))
  t.after(() => rmSync(base, { recursive: true, force: true }))
  const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  for (const dir of ['src', 'locale', 'scripts']) cpSync(join(repo, dir), join(base, dir), { recursive: true })
  mkdirSync(join(base, 'lib'))
  for (const file of ['package.json', 'cordis.patch.yml', 'icon.svg', 'lib/index.js']) cpSync(join(repo, file), join(base, file))
  rmSync(join(base, 'src/shared/build-id.js'), { force: true })
  execFileSync(process.execPath, [join(base, 'scripts/build-client.mjs')], { cwd: base })
  const manifest = JSON.parse(readFileSync(join(base, 'lib/build-manifest.json'), 'utf8'))
  assert.equal(manifest.buildId, computeBuildId(base))
  assert.equal(manifest.clientSha256, sha256File(join(base, 'lib/client.js')))
  assert.match(readFileSync(join(base, 'src/shared/build-id.js'), 'utf8'), new RegExp(manifest.buildId))
})
